// Writes supabase/functions/_shared/email-verification-copy.ts from src/data/email-verification/<lang>.json
// (the "email" part). The function image cannot import app files; a test keeps both in sync.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = 'src/data/email-verification';
const copy = Object.fromEntries(readdirSync(dir).filter((f) => f.endsWith('.json')).sort()
  .map((f) => [f.replace('.json', ''), JSON.parse(readFileSync(join(dir, f), 'utf8')).email]));
const out = `// Generated by scripts/i18n/build-email-verification-copy.mjs from src/data/email-verification. Do not edit.
export interface EmailVerificationCopy { subject: string; preheader: string; heading: string; intro: string; expires: string; ignore: string; footer: string }
export const EMAIL_VERIFICATION_COPY: Record<string, EmailVerificationCopy> = ${JSON.stringify(copy, null, 2)};
`;
writeFileSync('supabase/functions/_shared/email-verification-copy.ts', out);
console.log('languages:', Object.keys(copy).length);
