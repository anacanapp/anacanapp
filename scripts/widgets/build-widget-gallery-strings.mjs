// Writes the widget gallery names/descriptions for iOS (widget extension Localizable.strings, picked up by the
// synchronized AnacanTimerWidgetExt folder) and Android (values-<lang>/widget_strings.xml). Source:
// scripts/widgets/widget-gallery-strings.json. English stays in android/app/src/main/res/values/strings.xml.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
const src = JSON.parse(readFileSync(new URL('./widget-gallery-strings.json', import.meta.url), 'utf8'));
const en = src.languages.en;
const iosDir = { zh: 'zh-Hans', pt: 'pt-PT' };
const androidDir = { id: 'in' }; // Android's legacy qualifier for Indonesian
const iosEsc = (s) => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
const xmlEsc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/'/g, "\\'").replace(/"/g, '\\"');
for (const [lang, values] of Object.entries(src.languages)) {
  if (values.length !== src.keys.length) throw new Error(`WIDGET_STRINGS_LENGTH ${lang}`);
  const ios = `ios/App/AnacanTimerWidgetExt/${iosDir[lang] || lang}.lproj`;
  mkdirSync(ios, { recursive: true });
  writeFileSync(`${ios}/Localizable.strings`, `/* Generated by scripts/widgets/build-widget-gallery-strings.mjs */\n` +
    en.map((key, i) => `"${iosEsc(key)}" = "${iosEsc(values[i])}";`).join('\n') + '\n');
  if (lang === 'en') continue;
  const android = `android/app/src/main/res/values-${androidDir[lang] || lang}`;
  mkdirSync(android, { recursive: true });
  writeFileSync(`${android}/widget_strings.xml`, `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/widgets/build-widget-gallery-strings.mjs -->\n<resources>\n` +
    src.keys.map((key, i) => `    <string name="widget_${key}">${xmlEsc(values[i])}</string>`).join('\n') + '\n</resources>\n');
}
console.log('widget gallery strings:', Object.keys(src.languages).length);
