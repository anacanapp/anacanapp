#!/usr/bin/env python3
"""Builds the seed migration for the 100 Azerbaijani daily-quiz questions.
group_id = uuid5(NS, 'anacan-daily-quiz-v1-<n>') so translations added later (Admin → Bilik Yarışı → Tərcümə)
attach to the same question. Options are shuffled per question with a fixed seed; the correct index is stored.
Usage: python3 scripts/daily-quiz/build_seed.py [set] > supabase/migrations/<ts>_daily_quiz_seed_az[_<set>].sql
set 1 = questions_az.py (questions 1-100), set 2 = questions_az_2.py (101-200)."""
import json, os, random, sys, uuid
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import importlib
SET = int(sys.argv[1]) if len(sys.argv) > 1 else 1
Q = importlib.import_module('questions_az' if SET == 1 else f'questions_az_{SET}').Q
OFFSET = (SET - 1) * 100

NS = uuid.UUID('6f1d3c1a-7b0e-4c55-9a3e-2d6b1f0a9c11')
assert len(Q) == 100, len(Q)
CATS = {'pregnancy', 'baby_food', 'sleep', 'development', 'health', 'safety', 'postpartum'}

def lit(s): return "'" + s.replace("'", "''") + "'"

rows = []; idx = []
for n, (cat, q, opts, expl, src) in enumerate(Q, OFFSET + 1):
    assert cat in CATS and len(opts) == 4 and len(set(opts)) == 4, (n, q)
    assert '—' not in q + expl + ''.join(opts), n
    assert 5 <= len(q) <= 300 and len(expl) <= 600 and all(1 <= len(o) <= 120 for o in opts), n
    order = list(range(4)); random.Random(n * 7919).shuffle(order)
    shuffled = [opts[i] for i in order]; correct = order.index(0)
    idx.append(correct)
    gid = uuid.uuid5(NS, f'anacan-daily-quiz-v1-{n}')
    rows.append(f"({lit(str(gid))}::uuid, 'az', {lit(cat)}, {lit(q)}, {lit(json.dumps(shuffled, ensure_ascii=False))}::jsonb, {correct}, {lit(expl)}, {lit(src)}, true, {n})")

print("""-- Gündəlik Bilik Yarışı: 100 Azerbaijani questions (generated by scripts/daily-quiz/build_seed.py, set """ + str(SET) + """).
-- Idempotent: rows are keyed by (group_id, language); existing rows (edited in Admin) are left untouched.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '120s';
INSERT INTO public.quiz_questions (group_id, language, category, question, options, correct_index, explanation, source, is_active, sort_order)
VALUES
""" + ',\n'.join(rows) + """
ON CONFLICT (group_id, language) DO NOTHING;
COMMIT;""")
from collections import Counter
print('-- correct index distribution:', dict(Counter(idx)), file=sys.stderr)
