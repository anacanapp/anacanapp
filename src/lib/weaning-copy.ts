export type WeaningKey = keyof typeof WEANING_COPY;

/** Translated UI string of the weaning tool (tr with the Azerbaijani source as fallback). */
export const wt = (key: WeaningKey): string => tr(key, WEANING_COPY[key]);

/** Translated template with {placeholders} filled. */
export const wf = (key: WeaningKey, values: Record<string, unknown>): string => formatTr(key, WEANING_COPY[key], values);

/** Step name, numbered when the plan has several feeds of the same type ("Gündüz əmizdirməsi 2"). */
export const stepLabel = (s: Pick<WeaningStep, 'type' | 'n'>): string => {
  const label = wt(`weaning_ft_${s.type}` as WeaningKey);
  return s.n ? `${label} ${s.n}` : label;
};
