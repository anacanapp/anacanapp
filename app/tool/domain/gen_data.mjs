// Search folding for kid-exercises foldSearch: every BMP character (outside Hangul syllables) whose
// `normalize('NFD').replace(/[\u0300-\u036f]/g, '')` differs, as computed by this Node's ICU.
const fold = {};
for (let c = 0xa0; c < 0x10000; c++) {
  if (c >= 0xac00 && c <= 0xd7a3) continue; // Hangul syllables: decomposed algorithmically in Dart
  if (c >= 0xd800 && c <= 0xdfff) continue;
  const ch = String.fromCharCode(c);
  const out = ch.normalize('NFD').replace(/[\u0300-\u036f]/g, '');
  if (out !== ch) fold[ch] = out;
}
write('kid_exercises/data/search_fold_data.g.dart', 'src/lib/kid-exercises.ts (foldSearch: NFD + combining-mark removal)', [
  ['Character -> NFD without combining marks U+0300-U+036F (only characters that change).', 'Map<String, String>', 'searchFoldMap', fold],
]);
