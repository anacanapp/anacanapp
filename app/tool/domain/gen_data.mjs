// Generates the Dart data tables under app/lib/domain/**/data/*.g.dart from the ORIGINAL TypeScript modules
// (no retyping). Reproducible: `node app/tool/domain/gen_data.mjs` from the repo root (or anywhere).
// Tables that the TypeScript keeps in non-exported constants are read from the source text and evaluated.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { appDir, loadEntry, repoDir, TR_MARK } from './run_ts.mjs';

const libDir = path.join(appDir, 'lib', 'domain');

/** Evaluates `const NAME ... = <literal>;` from a TypeScript file (the literal must be plain data). */
function extractConst(file, name, scope = {}) {
  const src = readFileSync(path.join(repoDir, file), 'utf8');
  const start = src.search(new RegExp(`const ${name}\\b[^=]*=`));
  if (start < 0) throw new Error(`${name} not found in ${file}`);
  let i = src.indexOf('=', start) + 1;
  while (/\s/.test(src[i])) i++;
  const open = src[i], close = open === '[' ? ']' : '}';
  let depth = 0, j = i, str = null;
  for (; j < src.length; j++) {
    const c = src[j];
    if (str) { if (c === '\\') j++; else if (c === str) str = null; continue; }
    if (c === '/' && src[j + 1] === '/') { j = src.indexOf('\n', j); continue; }
    if (c === '/' && src[j + 1] === '*') { j = src.indexOf('*/', j) + 1; continue; }
    if (c === "'" || c === '"' || c === '`') { str = c; continue; }
    if (c === open) depth++;
    else if (c === close && --depth === 0) break;
  }
  const literal = src.slice(i, j + 1);
  return new Function(...Object.keys(scope), `return (${literal});`)(...Object.values(scope));
}

/** Strings produced by the keyed tr stub become { key, az }. */
function unkey(value) {
  if (typeof value === 'string' && value.startsWith(TR_MARK)) {
    const [, key, az] = value.split(TR_MARK);
    return { key, az };
  }
  if (Array.isArray(value)) return value.map(unkey);
  if (value && typeof value === 'object') return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, unkey(v)]));
  return value;
}

const dartString = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$').replace(/\n/g, '\\n').replace(/\r/g, '\\r')}'`;
function dart(value, indent = '') {
  const next = indent + '  ';
  if (value === null || value === undefined) return 'null';
  if (typeof value === 'boolean') return String(value);
  if (typeof value === 'number') {
    if (!Number.isFinite(value)) throw new Error('non-finite number in data');
    return String(value);
  }
  if (typeof value === 'string') return dartString(value);
  if (Array.isArray(value)) {
    if (value.every((v) => v === null || typeof v !== 'object')) return `[${value.map((v) => dart(v)).join(', ')}]`;
    return `[\n${value.map((v) => `${next}${dart(v, next)},`).join('\n')}\n${indent}]`;
  }
  const entries = Object.entries(value);
  if (!entries.length) return '{}';
  const key = (k) => (/^-?\d+$/.test(k) ? k : dartString(k));
  return `{\n${entries.map(([k, v]) => `${next}${key(k)}: ${dart(v, next)},`).join('\n')}\n${indent}}`;
}

function write(rel, source, decls) {
  const out = path.join(libDir, rel);
  mkdirSync(path.dirname(out), { recursive: true });
  const body = decls.map(([doc, type, name, value]) => `/// ${doc}\nconst ${type} ${name} = ${dart(value)};\n`).join('\n');
  writeFileSync(out, `// Ported from: ${source}\n// GENERATED by app/tool/domain/gen_data.mjs. Do not edit by hand.\n// ignore_for_file: prefer_single_quotes, lines_longer_than_80_chars\n\n${body}`);
  console.log('wrote', path.relative(appDir, out));
}

