#!/usr/bin/env node
// Ported from: src/data/partner-missions/*.json, src/data/postpartum-partner/*.json, src/lib/feature37-i18n.ts
//              (data sources of the partner feature)
//
// Generates the Dart data tables of the partner feature from the React sources, byte-for-byte reproducible
// (sorted languages, source key order, no timestamps):
//   app/lib/features/partner/generated/partner_missions_text.g.dart   ← src/data/partner-missions/<lang>.json
//   app/lib/features/partner/generated/postpartum_partner_text.g.dart ← src/data/postpartum-partner/<lang>.json
//   app/lib/features/partner/generated/partner_copy.g.dart            ← scripts/i18n/feature37-copy.json (used keys)
// Run from the repo root or app/:  node app/tool/partner/gen_partner_data.mjs
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '../../..');
const out = join(repo, 'app/lib/features/partner/generated');
mkdirSync(out, { recursive: true });

/** feature37Text keys the partner feature renders. */
const FEATURE37_KEYS = [
  'partner_link_step2', 'partner_link_title', 'partner_link_hint', 'partner_link_submit', 'partner_linked_ok',
  'pm_cycle_hidden', 'pm_chip_night', 'pm_chip_rest', 'pm_chip_buy', 'pm_chip_tea', 'pm_chip_on_way',
  'pm_birth_plan', 'pm_birth_plan_sub', 'pm_night_shift', 'pm_night_shift_sub', 'pm_biz_prepare', 'pm_biz_daily',
  'pm_biz_us', 'pm_birth_contractions', 'pm_birth_hospital', 'pm_birth_bag', 'pm_birth_title', 'pm_birth_sub',
  'pm_birth_sub_due', 'pm_ata_ai', 'ptour2_home_text', 'ptour2_together_text', 'ptour2_ai_text', 'ph_summary',
  'pp_settings', 'pn_title', 'pn_sub', 'pn_messages', 'pn_messages_sub', 'pn_thanks', 'pn_thanks_sub', 'pn_shopping',
  'pn_shopping_sub', 'pn_contractions', 'pn_contractions_sub', 'pn_sos', 'pn_sos_sub', 'pn_inbox_note',
];

const dartString = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$').replace(/\n/g, '\\n')}'`;

function dartValue(v, indent = '  ') {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'string') return dartString(v);
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  if (Array.isArray(v)) {
    if (v.length === 0) return 'const <Object?>[]';
    return `<Object?>[\n${v.map((x) => `${indent}  ${dartValue(x, indent + '  ')},`).join('\n')}\n${indent}]`;
  }
  const keys = Object.keys(v);
  return `<String, Object?>{\n${keys.map((k) => `${indent}  ${dartString(k)}: ${dartValue(v[k], indent + '  ')},`).join('\n')}\n${indent}}`;
}

const header = (source) => [
  '// GENERATED by app/tool/partner/gen_partner_data.mjs — do not edit.',
  `// Ported from: ${source}`,
  '// ignore_for_file: lines_longer_than_80_chars',
  '',
];

const languagesOf = (dir) => readdirSync(dir).filter((f) => f.endsWith('.json')).map((f) => f.slice(0, -5)).sort();

// ── partner missions: { key: [title, description] } ──
{
  const dir = join(repo, 'src/data/partner-missions');
  const lines = [...header('src/data/partner-missions/*.json'), '/// `PartnerMissionText` per app language: mission key → [title, description].',
    'const Map<String, Map<String, List<String>>> kPartnerMissionText = {'];
  for (const lang of languagesOf(dir)) {
    const data = JSON.parse(readFileSync(join(dir, `${lang}.json`), 'utf8'));
    lines.push(`  '${lang}': {`);
    for (const [key, value] of Object.entries(data)) lines.push(`    ${dartString(key)}: [${value.map(dartString).join(', ')}],`);
    lines.push('  },');
  }
  lines.push('};', '');
  writeFileSync(join(out, 'partner_missions_text.g.dart'), lines.join('\n'));
}

// ── postpartum partner guide (same shape as az.json) ──
{
  const dir = join(repo, 'src/data/postpartum-partner');
  const lines = [...header('src/data/postpartum-partner/*.json'), '/// `PostpartumPartnerText` per app language (same shape as az.json).',
    'const Map<String, Map<String, Object?>> kPostpartumPartnerText = {'];
  for (const lang of languagesOf(dir)) {
    const data = JSON.parse(readFileSync(join(dir, `${lang}.json`), 'utf8'));
    lines.push(`  '${lang}': ${dartValue(data, '  ')},`);
  }
  lines.push('};', '');
  writeFileSync(join(out, 'postpartum_partner_text.g.dart'), lines.join('\n'));
}

// ── feature37Text subset ──
{
  const copy = JSON.parse(readFileSync(join(repo, 'scripts/i18n/feature37-copy.json'), 'utf8'));
  const lines = [...header('scripts/i18n/feature37-copy.json (keys used by the partner feature)'),
    '/// `feature37Text` keys of the partner feature.', 'const Map<String, Map<String, String>> kPartnerFeature37Copy = {'];
  for (const lang of Object.keys(copy.languages).sort()) {
    lines.push(`  '${lang}': {`);
    for (const k of FEATURE37_KEYS) if (copy.languages[lang][k] != null) lines.push(`    ${dartString(k)}: ${dartString(copy.languages[lang][k])},`);
    lines.push('  },');
  }
  lines.push('};', '');
  writeFileSync(join(out, 'partner_copy.g.dart'), lines.join('\n'));
}

console.log(`wrote partner generated data (${FEATURE37_KEYS.length} feature37 keys)`);
