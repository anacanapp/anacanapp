#!/usr/bin/env node
// Ported from: src/data/illness/index.ts, src/data/pregnancy-loss/index.ts (data sources)
//
// Generates the per-language copy of the health screens from the React JSON files, byte-for-byte reproducible
// (source key order, no timestamps):
//   app/lib/features/health_screens/illness/illness_text.g.dart     src/data/illness/<lang>.json (25 languages)
//   app/lib/features/health_screens/loss/pregnancy_loss_text.g.dart src/data/pregnancy-loss/<lang>.json
// Run from the repo root or app/:  node app/tool/health_screens/gen_health_text.mjs   (--check: verify only)
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '../../..');
const app = join(repo, 'app');
const check = process.argv.includes('--check');

const dartString = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$').replace(/\n/g, '\\n')}'`;

function dartValue(v, indent = '  ') {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'string') return dartString(v);
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  if (Array.isArray(v)) {
    if (v.length === 0) return 'const <Object?>[]';
    return `<Object?>[\n${v.map((x) => `${indent}  ${dartValue(x, indent + '  ')},`).join('\n')}\n${indent}]`;
  }
  const keys = Object.keys(v);
  return `<String, Object?>{\n${keys.map((k) => `${indent}  ${dartString(k)}: ${dartValue(v[k], indent + '  ')},`).join('\n')}\n${indent}}`;
}

function generate(feature, constName, out, doc) {
  const dir = join(repo, 'src/data', feature);
  const langs = readdirSync(dir).filter((f) => f.endsWith('.json')).map((f) => f.slice(0, -5)).sort();
  const lines = [
    '// GENERATED by app/tool/health_screens/gen_health_text.mjs - do not edit.',
    `// Ported from: src/data/${feature}/*.json`,
    '// ignore_for_file: lines_longer_than_80_chars',
    '',
    `/// ${doc}`,
    `const Map<String, Map<String, Object?>> ${constName} = {`,
  ];
  for (const lang of langs) {
    const data = JSON.parse(readFileSync(join(dir, `${lang}.json`), 'utf8'));
    lines.push(`  '${lang}': ${dartValue(data, '  ')},`);
  }
  lines.push('};', '');
  const text = lines.join('\n');
  const path = join(app, out);
  if (check) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== text) {
      console.error(`${out} is out of date`);
      process.exitCode = 1;
    }
  } else {
    writeFileSync(path, text);
  }
  return langs.length;
}

const a = generate('illness', 'kIllnessText', 'lib/features/health_screens/illness/illness_text.g.dart', '`IllnessText` per app language (same shape as az.json).');
const b = generate('pregnancy-loss', 'kPregnancyLossText', 'lib/features/health_screens/loss/pregnancy_loss_text.g.dart', '`PregnancyLossText` per app language (same shape as az.json).');
console.log(`${check ? 'checked' : 'wrote'} illness_text.g.dart (${a} languages) and pregnancy_loss_text.g.dart (${b} languages)`);
