#!/usr/bin/env node
// Ported from: src/lib/feature37-i18n.ts, src/lib/followup-i18n.ts, src/data/recovery/index.ts (data sources)
//
// Generates the Dart data tables of the mommy home / recovery card from the React sources, byte-for-byte
// reproducible (sorted keys, no timestamps):
//   app/lib/features/home_mommy/copy/mommy_copy.g.dart  ← scripts/i18n/{feature37,followup36}-copy.json (used keys)
//   app/lib/features/recovery/recovery_text.g.dart      ← src/data/recovery/<lang>.json (all 25 languages)
// Run from the repo root or app/:  node app/tool/mommy/gen_mommy_data.mjs
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '../../..');
const app = join(repo, 'app');

const FEATURE37_KEYS = [
  'sfg_home_title', 'sfg_home_sub_before', 'sfg_home_sub_after',
  'period_banner_title', 'period_banner_body', 'period_start', 'period_card_title', 'period_day_n',
  'period_last_short', 'period_calendar', 'period_ask_today', 'period_continue', 'period_end',
  'period_saved', 'period_failed',
];
const FOLLOWUP_KEYS = ['ai_sleep', 'ai_feeding', 'ai_diaper'];

const dartString = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$').replace(/\n/g, '\\n')}'`;

function dartValue(v, indent = '  ') {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'string') return dartString(v);
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  if (Array.isArray(v)) {
    if (v.length === 0) return 'const <Object?>[]';
    return `<Object?>[\n${v.map((x) => `${indent}  ${dartValue(x, indent + '  ')},`).join('\n')}\n${indent}]`;
  }
  const keys = Object.keys(v);
  return `<String, Object?>{\n${keys.map((k) => `${indent}  ${dartString(k)}: ${dartValue(v[k], indent + '  ')},`).join('\n')}\n${indent}}`;
}

function table(name, copy, keys, doc) {
  const langs = Object.keys(copy.languages).sort();
  const lines = [`/// ${doc}`, `const Map<String, Map<String, String>> ${name} = {`];
  for (const lang of langs) {
    const entries = keys.filter((k) => copy.languages[lang][k] != null).map((k) => `    ${dartString(k)}: ${dartString(copy.languages[lang][k])},`);
    lines.push(`  '${lang}': {`, ...entries, '  },');
  }
  lines.push('};');
  return lines.join('\n');
}

// ── copy tables ──
const feature37 = JSON.parse(readFileSync(join(repo, 'scripts/i18n/feature37-copy.json'), 'utf8'));
const followup = JSON.parse(readFileSync(join(repo, 'scripts/i18n/followup36-copy.json'), 'utf8'));
const copyOut = [
  '// GENERATED by app/tool/mommy/gen_mommy_data.mjs — do not edit.',
  '// Ported from: scripts/i18n/feature37-copy.json, scripts/i18n/followup36-copy.json (keys used by the mommy home)',
  '// ignore_for_file: lines_longer_than_80_chars',
  '',
  table('kMommyFeature37Copy', feature37, FEATURE37_KEYS, '`feature37Text` keys of the mommy home (solid food entry, period banner).'),
  '',
  table('kMommyFollowupCopy', followup, FOLLOWUP_KEYS, '`followupText(`ai_<section>`)` of TrackerAIInsight.'),
  '',
].join('\n');
writeFileSync(join(app, 'lib/features/home_mommy/copy/mommy_copy.g.dart'), copyOut);

// ── recovery text ──
const dir = join(repo, 'src/data/recovery');
const langs = readdirSync(dir).filter((f) => f.endsWith('.json')).map((f) => f.slice(0, -5)).sort();
const recLines = [
  '// GENERATED by app/tool/mommy/gen_mommy_data.mjs — do not edit.',
  '// Ported from: src/data/recovery/*.json',
  '// ignore_for_file: lines_longer_than_80_chars',
  '',
  '/// `RecoveryText` per app language (same shape as az.json).',
  'const Map<String, Map<String, Object?>> kRecoveryText = {',
];
for (const lang of langs) {
  const data = JSON.parse(readFileSync(join(dir, `${lang}.json`), 'utf8'));
  recLines.push(`  '${lang}': ${dartValue(data, '  ')},`);
}
recLines.push('};', '');
writeFileSync(join(app, 'lib/features/recovery/recovery_text.g.dart'), recLines.join('\n'));
console.log(`wrote mommy_copy.g.dart (${FEATURE37_KEYS.length + FOLLOWUP_KEYS.length} keys) and recovery_text.g.dart (${langs.length} languages)`);
