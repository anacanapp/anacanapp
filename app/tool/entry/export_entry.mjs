#!/usr/bin/env node
// Ported from: (tool) — copies the entry-flow images from src/assets and countries.json into
// app/assets/images/entry/ and generates the Dart data tables of app/lib/features/entry/data/.
// Deterministic; run from anywhere: `node app/tool/entry/export_entry.mjs` (add `--check` to only verify).
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, existsSync, readdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
const app = join(root, 'app');
const assets = join(app, 'assets/images/entry');
const dataDir = join(app, 'lib/features/entry/data');
const check = process.argv.includes('--check');
let stale = 0;

function put(path, content) {
  const buf = Buffer.isBuffer(content) ? content : Buffer.from(content, 'utf8');
  if (existsSync(path) && readFileSync(path).equals(buf)) return;
  stale++;
  if (check) { console.error(`stale: ${path}`); return; }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, buf);
}
const dartStr = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$').replace(/\n/g, '\\n')}'`;

// ── Images ──
put(join(assets, 'brand-mark.png'), readFileSync(join(root, 'src/assets/brand-mark.png')));
for (const f of ['cycle', 'pregnancy', 'mother']) {
  put(join(assets, `onboarding/${f}-welcome.webp`), readFileSync(join(root, `src/assets/onboarding/${f}-welcome.webp`)));
}

// ── Countries (countries.json order) + flags ──
const countries = JSON.parse(readFileSync(join(root, 'countries.json'), 'utf8'));
for (const c of countries) {
  const b64 = c.flag.startsWith('data:') ? c.flag.split(',')[1] : c.flag;
  put(join(assets, `flags/${c.isoAlpha2.toLowerCase()}.png`), Buffer.from(b64, 'base64'));
}
put(join(dataDir, 'countries.g.dart'), `// GENERATED by app/tool/entry/export_entry.mjs from countries.json. Do not edit.
// Ported from: countries.json (id, name, isoAlpha2; flags → assets/images/entry/flags/<iso>.png)
// ignore_for_file: lines_longer_than_80_chars

/// (isoAlpha2, English name) in countries.json order.
const List<(String, String)> kCountryRows = [
${countries.map((c) => `  (${dartStr(c.isoAlpha2)}, ${dartStr(c.name)}),`).join('\n')}
];
`);

// ── Localized country names (localizedCountryName: ky bundled list, else Intl.DisplayNames(locale)) ──
const appLangSrc = readFileSync(join(root, 'src/lib/app-languages.ts'), 'utf8');
const langRows = [...appLangSrc.matchAll(/code:\s*'([a-z]{2})'[^}]*?locale:\s*'([A-Za-z-]+)'/g)].map((m) => [m[1], m[2]]);
if (langRows.length !== 25) throw new Error(`expected 25 languages, got ${langRows.length}`);
const ky = JSON.parse(readFileSync(join(root, 'src/data/country-names-ky.json'), 'utf8'));
const names = {};
for (const [code, locale] of langRows) {
  const dn = new Intl.DisplayNames([locale], { type: 'region' });
  names[code] = {};
  for (const c of countries) {
    let n = code === 'ky' ? ky[c.isoAlpha2] : undefined;
    if (!n) { try { n = dn.of(c.isoAlpha2) || c.name; } catch { n = c.name; } }
    names[code][c.isoAlpha2] = n;
  }
}
put(join(dataDir, 'country_names.g.dart'), `// GENERATED by app/tool/entry/export_entry.mjs (Node ${process.versions.node}, ICU ${process.versions.icu}). Do not edit.
// Ported from: src/lib/app-languages.ts (localizedCountryName), src/data/country-names-ky.json
// ignore_for_file: lines_longer_than_80_chars

/// language → ISO-2 → region name (\`Intl.DisplayNames(appLanguageLocale(lang), {type: 'region'})\`).
const Map<String, Map<String, String>> kCountryNames = {
${Object.entries(names).map(([l, m]) => `  ${dartStr(l)}: {${Object.entries(m).map(([k, v]) => `${dartStr(k)}: ${dartStr(v)}`).join(', ')}},`).join('\n')}
};
`);

// ── E-mail verification UI copy ──
const evDir = join(root, 'src/data/email-verification');
const ev = {};
for (const f of readdirSync(evDir).filter((f) => f.endsWith('.json')).sort()) ev[f.slice(0, -5)] = JSON.parse(readFileSync(join(evDir, f), 'utf8')).ui;
put(join(dataDir, 'email_verification_copy.g.dart'), `// GENERATED by app/tool/entry/export_entry.mjs from src/data/email-verification/*.json (ui part). Do not edit.
// Ported from: src/data/email-verification/index.ts
// ignore_for_file: lines_longer_than_80_chars

const Map<String, Map<String, String>> kEmailVerificationCopy = {
${Object.entries(ev).map(([l, m]) => `  ${dartStr(l)}: {${Object.entries(m).map(([k, v]) => `${dartStr(k)}: ${dartStr(v)}`).join(', ')}},`).join('\n')}
};
`);

// ── Promo copy used by AuthScreen ──
const prDir = join(root, 'src/data/promo');
const promo = {};
for (const f of readdirSync(prDir).filter((f) => f.endsWith('.json')).sort()) {
  const j = JSON.parse(readFileSync(join(prDir, f), 'utf8'));
  promo[f.slice(0, -5)] = { field_placeholder: j.field_placeholder, profile_title: j.profile_title, err_not_found: j.err_not_found };
}
put(join(dataDir, 'promo_copy.g.dart'), `// GENERATED by app/tool/entry/export_entry.mjs from src/data/promo/*.json (keys AuthScreen reads). Do not edit.
// Ported from: src/data/promo/index.ts
// ignore_for_file: lines_longer_than_80_chars

const Map<String, Map<String, String>> kPromoCopy = {
${Object.entries(promo).map(([l, m]) => `  ${dartStr(l)}: {${Object.entries(m).map(([k, v]) => `${dartStr(k)}: ${dartStr(v)}`).join(', ')}},`).join('\n')}
};
`);

// ── Onboarding copy used by AppIntroduction (+ stage names) ──
const onb = readFileSync(join(root, 'src/lib/onboarding-i18n.ts'), 'utf8');
const keys = ['start', 'companion', 'welcome_eyebrow', 'welcome_title', 'welcome_sub', 'feature_tracking', 'feature_tools', 'feature_community', 'own_pace'];
const onbCopy = {};
for (const k of keys) {
  const m = onb.match(new RegExp(`^  ${k}: (\\[.*\\]),\\s*$`, 'm'));
  if (!m) throw new Error(`onboarding key ${k} not found`);
  onbCopy[k] = Function(`return ${m[1]}`)();
}
const stageSrc = readFileSync(join(root, 'src/lib/stage-names.ts'), 'utf8');
const stage = Function(`return ${stageSrc.match(/STAGE_NAMES = (\{[\s\S]*?\}) as const/)[1]}`)();
put(join(dataDir, 'intro_copy.g.dart'), `// GENERATED by app/tool/entry/export_entry.mjs from src/lib/onboarding-i18n.ts + src/lib/stage-names.ts. Do not edit.
// Ported from: src/lib/onboarding-i18n.ts (ONBOARDING_COPY subset), src/lib/stage-names.ts (STAGE_NAMES)
// ignore_for_file: lines_longer_than_80_chars

/// ONBOARDING_LANGUAGES column order.
const List<String> kOnboardingLanguages = ['az', 'en', 'tr', 'ru', 'de', 'ar', 'ka', 'kk', 'uz'];

const Map<String, List<String>> kIntroCopy = {
${Object.entries(onbCopy).map(([k, v]) => `  ${dartStr(k)}: [${v.map(dartStr).join(', ')}],`).join('\n')}
};

/// [flow, bump, mommy] names per language.
const Map<String, List<String>> kStageNames = {
${Object.entries(stage).map(([k, v]) => `  ${dartStr(k)}: [${v.map(dartStr).join(', ')}],`).join('\n')}
};
`);

if (check && stale) process.exit(1);
console.log(check ? 'entry export up to date' : `entry export: ${stale} file(s) written`);
