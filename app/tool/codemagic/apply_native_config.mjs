// Codemagic Flutter builds: native-only configuration, the Flutter counterpart of
// scripts/codemagic/apply-native-config.mjs.
//
//   node app/tool/codemagic/apply_native_config.mjs ios|android
//     Before `flutter build`: writes the live AdMob app ID and the Customer.io Data In
//     settings (including the CDP write key) into gitignored native configuration only:
//       android: app/android/anacan-native.properties -> build.gradle.kts manifest
//                placeholder ${anacanAdmobAppId} and resValue strings anacan_customerio_*
//       ios:     app/ios/Flutter/AnacanNative.xcconfig -> $(ANACAN_ADMOB_APP_ID),
//                $(ANACAN_CUSTOMERIO_*) build settings (Info.plist AnacanCustomerIo* keys) and the public Google
//                sign-in ids $(ANACAN_GOOGLE_IOS_CLIENT_ID|_REVERSED_CLIENT_ID|_SERVER_CLIENT_ID) (Info.plist
//                GIDClientID, GIDServerClientID, URL scheme), read from the committed Firebase files (public_ids.mjs)
//
//   node app/tool/codemagic/apply_native_config.mjs verify ios|android
//     After `flutter build`: fails when the write key appears in any Dart / Flutter asset
//     output (AOT snapshot, kernel, flutter_assets, the dart-define file), in the build
//     tree and inside the built IPA / AAB / APK.
//
// Prints names and verdicts only, never values.
import { execFileSync } from 'node:child_process';
import { existsSync, lstatSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { readPublicIds } from './public_ids.mjs';

const appDir = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const env = process.env;
const fail = message => { console.error(`Native config failed: ${message}`); process.exit(1); };
const verify = process.argv[2] === 'verify';
const platform = verify ? process.argv[3] : process.argv[2];
if (!['ios', 'android'].includes(platform)) fail('usage: apply_native_config.mjs [verify] ios|android');
const writeKey = env.VITE_CUSTOMERIO_CDP_WRITE_KEY ?? '';

const paths = {
  android: join(appDir, 'android', 'anacan-native.properties'),
  ios: join(appDir, 'ios', 'Flutter', 'AnacanNative.xcconfig'),
};

if (verify) verifyOutput(); else applyConfig();

function applyConfig() {
  // AdMob: live app ID only, never Google's sample publisher.
  const admobName = platform === 'ios' ? 'VITE_ADMOB_IOS_APP_ID' : 'VITE_ADMOB_ANDROID_APP_ID';
  const admobId = env[admobName] ?? '';
  if (!/^ca-app-pub-\d{16}~\d{10}$/.test(admobId) || admobId.startsWith('ca-app-pub-3940256099942544~')) {
    fail(`${admobName} must be the live AdMob app ID`);
  }

  // Customer.io Data In: the write key lives only in native configuration.
  let customerIo = { enabled: 'false', environment: '', region: '', writeKey: '' };
  if (env.VITE_CUSTOMERIO_ENABLED === 'true') {
    const environment = env.VITE_CUSTOMERIO_ENVIRONMENT;
    if (!['production', 'sandbox'].includes(environment) || env.VITE_CUSTOMERIO_REGION !== 'EU' || !writeKey) {
      fail('Customer.io needs VITE_CUSTOMERIO_ENVIRONMENT, VITE_CUSTOMERIO_REGION=EU and VITE_CUSTOMERIO_CDP_WRITE_KEY');
    }
    // Plain token characters only: the value must survive .properties and .xcconfig syntax unchanged.
    if (!/^[A-Za-z0-9+/=_.:-]+$/.test(writeKey)) fail('VITE_CUSTOMERIO_CDP_WRITE_KEY has unexpected characters');
    customerIo = { enabled: 'true', environment, region: 'EU', writeKey };
  }

  const target = paths[platform];
  let content;
  if (platform === 'android') {
    content = [
      '# Generated by app/tool/codemagic/apply_native_config.mjs. Gitignored; never commit.',
      `admobAppId=${admobId}`,
      `customerIoEnabled=${customerIo.enabled}`,
      `customerIoEnvironment=${customerIo.environment}`,
      `customerIoRegion=${customerIo.region}`,
      `customerIoCdpWriteKey=${customerIo.writeKey}`,
    ];
  } else {
    let google;
    try {
      google = readPublicIds(resolve(appDir, '..'), env);
    } catch (error) {
      fail(error.message);
    }
    // In .xcconfig "//" starts a comment; "/$()/" expands to "//" at build time.
    const xc = value => value.replaceAll('//', '/$()/');
    content = [
      '// Generated by app/tool/codemagic/apply_native_config.mjs. Gitignored; never commit.',
      `ANACAN_ADMOB_APP_ID = ${xc(admobId)}`,
      `ANACAN_CUSTOMERIO_ENABLED = ${customerIo.enabled}`,
      `ANACAN_CUSTOMERIO_ENVIRONMENT = ${customerIo.environment}`,
      `ANACAN_CUSTOMERIO_REGION = ${customerIo.region}`,
      `ANACAN_CUSTOMERIO_CDP_WRITE_KEY = ${xc(customerIo.writeKey)}`,
      `ANACAN_GOOGLE_IOS_CLIENT_ID = ${google.ANACAN_GOOGLE_IOS_CLIENT_ID}`,
      `ANACAN_GOOGLE_REVERSED_CLIENT_ID = ${google.ANACAN_GOOGLE_REVERSED_CLIENT_ID}`,
      `ANACAN_GOOGLE_SERVER_CLIENT_ID = ${google.ANACAN_GOOGLE_SERVER_CLIENT_ID}`,
    ];
  }
  assertIgnored(target);
  writeFileSync(target, content.join('\n') + '\n', { mode: 0o600 });
  console.log(`Native config OK for ${platform}: AdMob live app ID set, Customer.io ${customerIo.environment || 'off'}`
    + ` (${relative(appDir, target)}).`);
}

// The generated file holds a private value: refuse to write it where Git would pick it up.
function assertIgnored(file) {
  try {
    execFileSync('git', ['check-ignore', '-q', file], { cwd: appDir, stdio: 'ignore' });
  } catch (error) {
    if (error.status === 1) fail(`${relative(appDir, file)} is not gitignored`);
    // status 128 / ENOENT: not a Git checkout or no git binary; nothing to protect.
  }
}

function verifyOutput() {
  if (!writeKey) {
    console.log(`Write-key scan skipped for ${platform}: VITE_CUSTOMERIO_CDP_WRITE_KEY is not set.`);
    return;
  }
  const needles = [Buffer.from(writeKey, 'utf8'), Buffer.from(writeKey, 'utf16le')];
  const contains = buffer => needles.some(needle => buffer.includes(needle));
  const hits = [];
  let scanned = 0;
  const check = (label, buffer) => { scanned += 1; if (contains(buffer)) hits.push(label); };

  // Dart / Flutter outputs in the build tree. Native outputs (resources.arsc, Info.plist) are
  // expected to hold the key and are not scanned.
  const isDartOutput = path => {
    const name = basename(path);
    if (['app.so', 'libapp.so', 'app.dill', 'kernel_blob.bin'].includes(name)) return true;
    if (path.includes('/flutter_assets/')) return true;
    return platform === 'ios' && name === 'App' && path.includes('/App.framework/');
  };
  const walk = dir => {
    if (!existsSync(dir)) return;
    for (const name of readdirSync(dir)) {
      const path = join(dir, name);
      const stat = lstatSync(path);
      if (stat.isSymbolicLink()) continue;
      if (stat.isDirectory()) walk(path);
      else if (stat.isFile() && isDartOutput(path)) check(relative(appDir, path), readFileSync(path));
    }
  };
  walk(join(appDir, 'build', platform === 'ios' ? 'ios' : 'app'));
  walk(join(appDir, '.dart_tool', 'flutter_build'));

  const definesFile = env.DART_DEFINES_FILE || join(appDir, 'build', 'codemagic', 'dart_defines.json');
  if (existsSync(definesFile)) check(relative(appDir, definesFile), readFileSync(definesFile));

  // Final packages: only the Dart snapshot and Flutter assets entries.
  const archives = platform === 'ios'
    ? listFiles(join(appDir, 'build', 'ios', 'ipa'), '.ipa')
    : [...listFiles(join(appDir, 'build', 'app', 'outputs', 'bundle', 'release'), '.aab'),
      ...listFiles(join(appDir, 'build', 'app', 'outputs', 'flutter-apk'), '.apk')];
  const archiveEntry = platform === 'ios'
    ? /^Payload\/[^/]+\.app\/Frameworks\/App\.framework\//
    : /^(base\/)?(lib\/[^/]+\/libapp\.so$|assets\/flutter_assets\/)/;
  for (const archive of archives) {
    let entries;
    try {
      entries = execFileSync('unzip', ['-Z1', archive], { encoding: 'utf8', maxBuffer: 64 << 20 }).split('\n');
    } catch (error) { fail(`cannot list ${relative(appDir, archive)} (${error.code ?? error.status})`); }
    for (const entry of entries.filter(entry => archiveEntry.test(entry) && !entry.endsWith('/'))) {
      const buffer = execFileSync('unzip', ['-p', archive, entry], { maxBuffer: 512 << 20 });
      check(`${basename(archive)}:${entry}`, buffer);
    }
  }

  if (hits.length) fail(`Customer.io write key found in Dart/Flutter output: ${hits.join(', ')}`);
  if (!archives.length || scanned < 2) fail(`no ${platform} Dart output found to scan; run after flutter build`);
  console.log(`Write-key scan OK for ${platform}: ${scanned} Dart/asset files, ${archives.length} package(s).`);
}

function listFiles(dir, extension) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).filter(name => name.endsWith(extension)).map(name => join(dir, name));
}
