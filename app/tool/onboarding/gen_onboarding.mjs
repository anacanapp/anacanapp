#!/usr/bin/env node
// Reproducible import of the onboarding / premium bundled data from the React app.
//
//   node app/tool/onboarding/gen_onboarding.mjs          (from the repo root or app/)
//
// 1. Copies the companion mascot images src/assets/onboarding/*.webp (+ manifest.json) to
//    app/assets/images/onboarding/ and checks every file against the manifest's sha256.
// 2. Generates app/lib/features/onboarding/data/onboarding_copy.g.dart from src/lib/onboarding-i18n.ts
//    (ONBOARDING_LANGUAGES, ONBOARDING_COPY) and src/lib/stage-names.ts (STAGE_NAMES).
// 3. Generates app/lib/features/onboarding/data/onboarding_features_copy.g.dart from
//    scripts/i18n/onboarding-features-copy.json.
// 4. Generates app/lib/native/purchases/data/premium_copy.g.dart from scripts/i18n/premium-copy.json.
// Re-running reproduces the files byte for byte.
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const toolDir = path.dirname(fileURLToPath(import.meta.url));
const appDir = path.resolve(toolDir, '../..');
const repoDir = path.resolve(appDir, '..');
const src = (p) => path.join(repoDir, p);
const out = (p) => path.join(appDir, p);

// ── 1. images ──
const assetSrc = src('src/assets/onboarding');
const assetOut = out('assets/images/onboarding');
mkdirSync(assetOut, { recursive: true });
const manifest = JSON.parse(readFileSync(path.join(assetSrc, 'manifest.json'), 'utf8'));
const expected = new Map(manifest.files.map((f) => [f.file, f.sha256]));
let copied = 0;
for (const file of readdirSync(assetSrc).filter((f) => f.endsWith('.webp')).sort()) {
  const bytes = readFileSync(path.join(assetSrc, file));
  const sha = createHash('sha256').update(bytes).digest('hex');
  if (expected.has(file) && expected.get(file) !== sha) throw new Error(`sha256 mismatch for ${file}`);
  copyFileSync(path.join(assetSrc, file), path.join(assetOut, file));
  copied++;
}
copyFileSync(path.join(assetSrc, 'manifest.json'), path.join(assetOut, 'manifest.json'));

// ── helpers ──
const dartString = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$').replace(/\n/g, '\\n')}'`;
function objectLiteral(file, startMarker, endMarker) {
  const text = readFileSync(src(file), 'utf8');
  const start = text.indexOf(startMarker);
  if (start < 0) throw new Error(`${startMarker} not found in ${file}`);
  const open = text.indexOf('{', start);
  const end = text.indexOf(endMarker, open);
  return vm.runInNewContext(`(${text.slice(open, end + endMarker.indexOf('}') + 1)})`);
}
function arrayLiteral(file, startMarker) {
  const text = readFileSync(src(file), 'utf8');
  const start = text.indexOf(startMarker);
  const open = text.indexOf('[', start);
  const close = text.indexOf(']', open);
  return vm.runInNewContext(`(${text.slice(open, close + 1)})`);
}

// ── 2. onboarding copy ──
const languages = arrayLiteral('src/lib/onboarding-i18n.ts', 'export const ONBOARDING_LANGUAGES');
const copy = objectLiteral('src/lib/onboarding-i18n.ts', 'export const ONBOARDING_COPY', '\n} as const');
const stageNames = objectLiteral('src/lib/stage-names.ts', 'export const STAGE_NAMES', '\n} as const');
let dart = `// GENERATED by app/tool/onboarding/gen_onboarding.mjs — do not edit.
// Ported from: src/lib/onboarding-i18n.ts (ONBOARDING_LANGUAGES, ONBOARDING_COPY), src/lib/stage-names.ts (STAGE_NAMES)
// ignore_for_file: lines_longer_than_80_chars

/// Column order of [kOnboardingCopy].
const List<String> kOnboardingLanguages = [${languages.map(dartString).join(', ')}];

/// Reviewed bundled onboarding copy (${Object.keys(copy).length} keys × ${languages.length} languages).
const Map<String, List<String>> kOnboardingCopy = {
`;
for (const [key, values] of Object.entries(copy)) {
  if (values.length !== languages.length) throw new Error(`${key}: ${values.length} columns`);
  dart += `  ${dartString(key)}: [${values.map(dartString).join(', ')}],\n`;
}
dart += `};

/// Mode labels [flow, bump, mommy] per app language.
const Map<String, List<String>> kStageNames = {
`;
for (const [lang, names] of Object.entries(stageNames)) dart += `  ${dartString(lang)}: [${names.map(dartString).join(', ')}],\n`;
dart += '};\n';
mkdirSync(out('lib/features/onboarding/data'), { recursive: true });
writeFileSync(out('lib/features/onboarding/data/onboarding_copy.g.dart'), dart);

// ── 3. onboarding feature labels ──
const features = JSON.parse(readFileSync(src('scripts/i18n/onboarding-features-copy.json'), 'utf8'));
let fd = `// GENERATED by app/tool/onboarding/gen_onboarding.mjs — do not edit.
// Ported from: scripts/i18n/onboarding-features-copy.json (schema ${features.schema})
// ignore_for_file: lines_longer_than_80_chars

/// Onboarding benefit labels per app language and feature key.
const Map<String, Map<String, String>> kOnboardingFeatureCopy = {
`;
for (const [lang, labels] of Object.entries(features.languages)) {
  fd += `  ${dartString(lang)}: {\n`;
  for (const [key, label] of Object.entries(labels)) fd += `    ${dartString(key)}: ${dartString(label)},\n`;
  fd += '  },\n';
}
fd += '};\n';
writeFileSync(out('lib/features/onboarding/data/onboarding_features_copy.g.dart'), fd);

// ── 4. premium catalog copy ──
const premium = JSON.parse(readFileSync(src('scripts/i18n/premium-copy.json'), 'utf8'));
let pd = `// GENERATED by app/tool/onboarding/gen_onboarding.mjs — do not edit.
// Ported from: scripts/i18n/premium-copy.json (schema ${premium.schema}, sourceHash ${premium.sourceHash})
// ignore_for_file: lines_longer_than_80_chars

/// contentTranslationKey(row, field) → language → text, for premium_features / premium_plans rows.
const Map<String, Map<String, String>> kPremiumCopy = {
`;
for (const [key, values] of Object.entries(premium.values)) {
  pd += `  ${dartString(key)}: {\n`;
  for (const [lang, text] of Object.entries(values)) pd += `    ${dartString(lang)}: ${dartString(text)},\n`;
  pd += '  },\n';
}
pd += '};\n';
mkdirSync(out('lib/native/purchases/data'), { recursive: true });
writeFileSync(out('lib/native/purchases/data/premium_copy.g.dart'), pd);

// ── 5. Intl tables (Node ICU) for onboardingDate / currency formatting ──
const appLanguages = [...readFileSync(src('src/lib/app-languages.ts'), 'utf8').matchAll(/code: '([a-z]+)',[^}]*locale: '([A-Za-z-]+)'/g)].map((m) => [m[1], m[2]]);
const CURRENCIES = ['USD', 'EUR', 'GBP', 'AZN', 'TRY', 'RUB', 'KZT', 'UZS', 'GEL', 'UAH', 'INR', 'JPY', 'KRW', 'CNY', 'IDR', 'VND', 'PLN', 'SEK',
  'BRL', 'CAD', 'AUD', 'AED', 'SAR', 'KGS', 'CHF', 'NOK', 'DKK', 'CZK', 'HUF', 'RON', 'MXN', 'EGP', 'PKR', 'TJS', 'TMT', 'MDL', 'BYN', 'ILS',
  'THB', 'MYR', 'PHP', 'SGD', 'HKD', 'TWD', 'NZD', 'ZAR', 'NGN', 'CLP', 'COP', 'PEN', 'ARS', 'QAR', 'KWD', 'BGN', 'RSD', 'AMD', 'IQD', 'JOD', 'MAD'];
const sample = new Date('2026-09-22T12:00:00Z');
let id = `// GENERATED by app/tool/onboarding/gen_onboarding.mjs — do not edit.
// Ported from: Intl.DateTimeFormat(locale, {year:'numeric', month:'2-digit', day:'2-digit', timeZone:'UTC'}) and
// Intl.NumberFormat(locale, {style:'currency', currency}) as rendered by Node ${process.version} ICU ${process.versions.icu}
// for the app language locales of src/lib/app-languages.ts.
// ignore_for_file: lines_longer_than_80_chars

/// Numeric date template per language: {d} day, {M} month, {y} year (2-digit day/month).
const Map<String, String> kOnbDateTemplates = {
`;
for (const [code, locale] of appLanguages) {
  const parts = new Intl.DateTimeFormat(locale, { year: 'numeric', month: '2-digit', day: '2-digit', timeZone: 'UTC' }).formatToParts(sample);
  id += `  ${dartString(code)}: ${dartString(parts.map((p) => p.type === 'day' ? '{d}' : p.type === 'month' ? '{M}' : p.type === 'year' ? '{y}' : p.value).join(''))},\n`;
}
id += `};

/// Currency layout per language: {n} the number, {c} the symbol.
const Map<String, String> kCurrencyTemplates = {
`;
for (const [code, locale] of appLanguages) {
  const parts = new Intl.NumberFormat(locale, { style: 'currency', currency: 'USD' }).formatToParts(2.5);
  let t = '', inNumber = false;
  for (const p of parts) {
    if (['integer', 'group', 'decimal', 'fraction', 'minusSign'].includes(p.type)) { if (!inNumber) { t += '{n}'; inNumber = true; } }
    else { inNumber = false; t += p.type === 'currency' ? '{c}' : p.value; }
  }
  id += `  ${dartString(code)}: ${dartString(t)},\n`;
}
id += `};

/// Currency symbol per language and ISO code.
const Map<String, Map<String, String>> kCurrencySymbols = {
`;
for (const [code, locale] of appLanguages) {
  id += `  ${dartString(code)}: {`;
  id += CURRENCIES.map((c) => `${dartString(c)}: ${dartString(new Intl.NumberFormat(locale, { style: 'currency', currency: c }).formatToParts(1).find((p) => p.type === 'currency').value)}`).join(', ');
  id += '},\n';
}
id += `};

/// Fraction digits per ISO code (others: 2).
const Map<String, int> kCurrencyDigits = {${CURRENCIES.map((c) => [c, new Intl.NumberFormat('en', { style: 'currency', currency: c }).resolvedOptions().maximumFractionDigits]).filter(([, d]) => d !== 2).map(([c, d]) => `${dartString(c)}: ${d}`).join(', ')}};
`;
writeFileSync(out('lib/features/onboarding/data/onboarding_intl.g.dart'), id);

console.log(`onboarding: ${copied} images, ${Object.keys(copy).length} copy keys, ${Object.keys(features.languages).length} feature languages, ${Object.keys(premium.values).length} premium rows`);
if (!existsSync(assetOut)) process.exit(1);
