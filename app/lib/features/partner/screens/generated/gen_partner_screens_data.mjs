#!/usr/bin/env node
// Ported from: scripts/i18n/feature37-copy.json (feature37Text keys of the partner screens)
//
// Generates the feature37 copy table of the partner screens from the React source, byte-for-byte reproducible
// (sorted languages, source key order, no timestamps):
//   app/lib/features/partner/screens/generated/partner_screens_copy.g.dart <- scripts/i18n/feature37-copy.json (used keys)
// The partner core keys stay in app/tool/partner/gen_partner_data.mjs (partner_copy.g.dart).
// Run from the repo root:  node app/lib/features/partner/screens/generated/gen_partner_screens_data.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '../../../../../..');

/** feature37Text keys the partner screens render (besides the ones of the partner core). */
const FEATURE37_PREFIXES = /^(ph_|ns_|bp_|family_)/;

const dartString = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$').replace(/\n/g, '\\n').replace(/\r/g, '\\r')}'`;

const copy = JSON.parse(readFileSync(join(repo, 'scripts/i18n/feature37-copy.json'), 'utf8'));
const keys = Object.keys(copy.languages.en).filter((k) => FEATURE37_PREFIXES.test(k));
const lines = [
  '// GENERATED by app/lib/features/partner/screens/generated/gen_partner_screens_data.mjs - do not edit.',
  '// Ported from: scripts/i18n/feature37-copy.json (keys used by the partner screens)',
  '// ignore_for_file: lines_longer_than_80_chars',
  '',
  '/// `feature37Text` keys of the partner screens (ph_*, ns_*, bp_*, family_*).',
  'const Map<String, Map<String, String>> kPartnerScreensFeature37Copy = {',
];
for (const lang of Object.keys(copy.languages).sort()) {
  lines.push(`  '${lang}': {`);
  for (const key of keys) {
    const value = copy.languages[lang][key];
    if (typeof value === 'string') lines.push(`    ${dartString(key)}: ${dartString(value)},`);
  }
  lines.push('  },');
}
lines.push('};', '');
writeFileSync(join(here, 'partner_screens_copy.g.dart'), lines.join('\n'));
