#!/usr/bin/env node
// Generates the data tables of the commerce feature from the React sources:
//   qaygicash/qc_intl.g.dart        Intl percent affixes + short-date templates (Node ICU, the 25 app locales)
//   sponsor/sponsor_copy.g.dart     src/data/sponsor/<lang>.json (createFeatureText packs)
//   partner_shop/partner_catalog.g.dart  src/data/{olivia,rossmann}-products.json (sku → collections, "why" lines)
// Run from the repo root:  node app/lib/features/commerce/gen_commerce_data.mjs
// Re-running reproduces the files byte for byte (same Node ICU).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '../../../..');
const read = (p) => JSON.parse(readFileSync(join(root, p), 'utf8'));
const lit = (v) => JSON.stringify(v).replace(/\$/g, '\\$');

// The 25 app languages with their locale tags (app_languages.g.dart: (code, english, native, tag, flag)).
const langSrc = readFileSync(join(root, 'app/lib/core/i18n/generated/app_languages.g.dart'), 'utf8');
const LANGS = [...langSrc.matchAll(/\('(\w+)', '(?:[^'\\]|\\.)*', '(?:[^'\\]|\\.)*', '([\w-]+)'/g)].map((m) => [m[1], m[2]]);
if (LANGS.length !== 25) throw new Error(`expected 25 languages, got ${LANGS.length}`);

const header = (from) => `// GENERATED by app/lib/features/commerce/gen_commerce_data.mjs. Do not edit.\n// Ported from: ${from}\n// ignore_for_file: lines_longer_than_80_chars\n\n`;

// ── qc_intl.g.dart ──────────────────────────────────────────────────────────────────────────────
{
  let out = header('src/lib/qaygicash.ts (Intl.NumberFormat percent, toLocaleDateString {day, month: short[, year]})');
  out += '/// `new Intl.NumberFormat(locale, {style: "percent"})` affixes around the number: (prefix, suffix).\n';
  out += 'const Map<String, (String, String)> kQcPercentAffixes = {\n';
  for (const [code, tag] of LANGS) {
    const s = new Intl.NumberFormat(tag, { style: 'percent', numberingSystem: 'latn' }).format(0.05);
    const i = s.indexOf('5');
    out += `  ${lit(code)}: (${lit(s.slice(0, i))}, ${lit(s.slice(i + 1))}),\n`;
  }
  out += '};\n\n';
  out += '/// Short-date templates (`{d}`, `{M}`, `{y}`; Latin digits) and the 12 short month names: (dm, dmy, months).\n';
  out += 'const Map<String, (String, String, List<String>)> kQcShortDates = {\n';
  const template = (tag, year) => {
    const f = new Intl.DateTimeFormat(tag, { day: 'numeric', month: 'short', ...(year ? { year: 'numeric' } : {}), numberingSystem: 'latn', timeZone: 'UTC' });
    return f.formatToParts(new Date(Date.UTC(2031, 0, 23))).map((p) => (p.type === 'day' ? '{d}' : p.type === 'month' ? '{M}' : p.type === 'year' ? '{y}' : p.value)).join('');
  };
  for (const [code, tag] of LANGS) {
    const f = new Intl.DateTimeFormat(tag, { day: 'numeric', month: 'short', numberingSystem: 'latn', timeZone: 'UTC' });
    const months = Array.from({ length: 12 }, (_, m) => f.formatToParts(new Date(Date.UTC(2031, m, 23))).find((p) => p.type === 'month').value);
    out += `  ${lit(code)}: (${lit(template(tag, false))}, ${lit(template(tag, true))}, <String>[${months.map(lit).join(', ')}]),\n`;
  }
  out += '};\n';
  writeFileSync(join(here, 'qaygicash/qc_intl.g.dart'), out);
}

// ── sponsor_copy.g.dart ─────────────────────────────────────────────────────────────────────────
{
  let out = header('src/data/sponsor/*.json (createFeatureText: own language, else en, else az)');
  out += 'const Map<String, Map<String, String>> kSponsorCopy = {\n';
  for (const [code] of LANGS) {
    let pack;
    try { pack = read(`src/data/sponsor/${code}.json`); } catch { continue; }
    out += `  ${lit(code)}: {${Object.entries(pack).map(([k, v]) => `${lit(k)}: ${lit(v)}`).join(', ')}},\n`;
  }
  out += '};\n';
  writeFileSync(join(here, 'sponsor/sponsor_copy.g.dart'), out);
}

// ── partner_catalog.g.dart ──────────────────────────────────────────────────────────────────────
{
  let out = header('src/lib/olivia-catalog.ts, src/lib/rossmann-catalog.ts (src/data/{olivia,rossmann}-products.json: the curated per-collection "why" lines)');
  out += '/// Partner slug → sku → (collections, why per collection).\n';
  out += 'const Map<String, Map<String, (List<String>, Map<String, String>)>> kCuratedPartnerCatalog = {\n';
  for (const slug of ['olivia', 'rossmann']) {
    const c = read(`src/data/${slug}-products.json`);
    out += `  ${lit(slug)}: {\n`;
    for (const p of c.products) {
      out += `    ${lit(p.sku)}: (<String>[${p.collections.map(lit).join(', ')}], <String, String>{${Object.entries(p.why).map(([k, v]) => `${lit(k)}: ${lit(v)}`).join(', ')}}),\n`;
    }
    out += '  },\n';
  }
  out += '};\n';
  writeFileSync(join(here, 'partner_shop/partner_catalog.g.dart'), out);
}
console.log('commerce data generated');
