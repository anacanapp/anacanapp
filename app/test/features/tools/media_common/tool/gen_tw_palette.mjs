// Generates app/lib/features/tools/media_common/tw_palette.g.dart from the TwColors class of
// app/lib/design/tokens/tailwind.g.dart (name-shade → token lookup for DB-stored Tailwind gradient classes).
// Run from the repo root: node app/test/features/tools/media_common/tool/gen_tw_palette.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync('app/lib/design/tokens/tailwind.g.dart', 'utf8');
const body = src.slice(src.indexOf('abstract final class TwColors'));
const entries = [...body.matchAll(/static const Color ([a-z]+?)(\d+) = /g)].map((m) => [m[1], m[2]]);
const lines = [
  '// GENERATED by app/test/features/tools/media_common/tool/gen_tw_palette.mjs - do not edit',
  '// Ported from: tailwind.config.ts (Tailwind v3 default palette, via app/lib/design/tokens/tailwind.g.dart)',
  "import 'package:flutter/painting.dart';",
  '',
  "import '../../../design/tokens/tailwind.g.dart';",
  '',
  '/// `<name>-<shade>` → Tailwind colour (plus `white` / `black`).',
  'const Map<String, Color> kTwPalette = <String, Color>{',
  "  'white': TwColors.white,",
  "  'black': TwColors.black,",
  ...entries.map(([name, shade]) => `  '${name}-${shade}': TwColors.${name}${shade},`),
  '};',
  '',
];
writeFileSync('app/lib/features/tools/media_common/tw_palette.g.dart', lines.join('\n'));
console.log(`${entries.length} colours`);
