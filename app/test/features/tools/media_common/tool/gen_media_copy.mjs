// Generates app/lib/features/tools/media_common/media_copy.g.dart from the React sources the AI & media tools read:
//   scripts/i18n/followup36-copy.json  (fairytale_unicorn, fairytale_name_placeholder, fairytale_hero_placeholder)
//   src/lib/fiction-names.ts           (EXAMPLES)
// Run from the repository root:  node app/test/features/tools/media_common/tool/gen_media_copy.mjs
import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const dartString = (s) => JSON.stringify(s).replace(/\$/g, '\\$');

const followup = JSON.parse(read('scripts/i18n/followup36-copy.json')).languages;
const keys = ['fairytale_unicorn', 'fairytale_name_placeholder', 'fairytale_hero_placeholder'];

const fiction = read('src/lib/fiction-names.ts');
const from = fiction.indexOf('{', fiction.indexOf('const EXAMPLES'));
const to = fiction.indexOf('}', from);
const examples = (0, eval)(`(${fiction.slice(from, to + 1)})`);

const lines = [
  '// Ported from: scripts/i18n/followup36-copy.json (fairytale_* keys), src/lib/fiction-names.ts (EXAMPLES)',
  '// GENERATED by app/test/features/tools/media_common/tool/gen_media_copy.mjs. Do not edit by hand.',
  '// ignore_for_file: prefer_single_quotes, lines_longer_than_80_chars',
  '',
  '/// `followupText` keys of the fairy tale tool.',
  'const Map<String, Map<String, String>> kMediaFollowupCopy = {',
];
for (const [lang, values] of Object.entries(followup)) {
  const picked = keys.filter((k) => typeof values[k] === 'string');
  if (!picked.length) continue;
  lines.push(`  '${lang}': {`);
  for (const k of picked) lines.push(`    '${k}': ${dartString(values[k])},`);
  lines.push('  },');
}
lines.push('};', '', '/// Fictional example child names (`EXAMPLES` of fiction-names.ts).', 'const Map<String, String> kFictionNames = {');
for (const [lang, name] of Object.entries(examples)) lines.push(`  '${lang}': ${dartString(name)},`);
lines.push('};', '');

const target = path.join(root, 'app/lib/features/tools/media_common/media_copy.g.dart');
fs.writeFileSync(target, lines.join('\n'));
console.log(`wrote ${path.relative(root, target)}`);
