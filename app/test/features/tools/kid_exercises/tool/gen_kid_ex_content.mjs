// Generates the bundled content of Uşaq məşqləri (tool.kid-exercises) from the React sources:
//   app/assets/kid_exercises/<lang>.json   ← src/data/kid-exercises/<lang>.json (verbatim; az.json is the source)
//   app/assets/exercises/<set>/<file>.webp ← public/exercises/<set>/<file>.webp (exerciseImage(id), byte-identical)
//   app/lib/features/tools/kid_exercises/kid_ex_ui_az.g.dart ← src/data/kid-exercises/ui-az.ts (KIDEX_UI_AZ)
// Run from the repository root:  node app/test/features/tools/kid_exercises/tool/gen_kid_ex_content.mjs [--check]
// --check writes nothing and exits 1 when a generated file differs from its source.
import { build } from 'esbuild';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const root = process.cwd();
const check = process.argv.includes('--check');
const out = (p) => path.join(root, p);

async function load(source) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'anacan-kidex-'));
  const outfile = path.join(dir, 'entry.mjs');
  await build({
    stdin: { contents: source, resolveDir: root, loader: 'ts' },
    bundle: true, platform: 'node', format: 'esm', target: 'node20', outfile, logLevel: 'error',
    alias: { '@': path.join(root, 'src') },
  });
  return import(pathToFileURL(outfile).href);
}

const dartString = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$').replace(/\n/g, '\\n')}'`;
const files = new Map();

const dataDir = out('src/data/kid-exercises');
for (const f of fs.readdirSync(dataDir).filter((f) => /^[a-z]{2}\.json$/.test(f)).sort()) {
  files.set(`app/assets/kid_exercises/${f}`, fs.readFileSync(path.join(dataDir, f)));
}

const images = out('public/exercises');
for (const set of fs.readdirSync(images).sort()) {
  const dir = path.join(images, set);
  if (!fs.statSync(dir).isDirectory()) continue;
  for (const f of fs.readdirSync(dir).filter((f) => f.endsWith('.webp')).sort()) {
    files.set(`app/assets/exercises/${set}/${f}`, fs.readFileSync(path.join(dir, f)));
  }
}

const ui = await load("export { KIDEX_UI_AZ } from '@/data/kid-exercises/ui-az';");
const lines = [
  '// Ported from: src/data/kid-exercises/ui-az.ts (KIDEX_UI_AZ)',
  '// GENERATED by app/test/features/tools/kid_exercises/tool/gen_kid_ex_content.mjs. Do not edit by hand.',
  '// ignore_for_file: lines_longer_than_80_chars',
  '',
  '/// `KIDEX_UI_AZ`: the Azerbaijani UI strings (every locale file has the same keys).',
  'const Map<String, String> kKidExUiAz = {',
  ...Object.entries(ui.KIDEX_UI_AZ).map(([k, v]) => `  '${k}': ${dartString(v)},`),
  '};',
  '',
];
files.set('app/lib/features/tools/kid_exercises/kid_ex_ui_az.g.dart', Buffer.from(lines.join('\n')));

let drift = 0;
for (const [p, bytes] of files) {
  const current = fs.existsSync(out(p)) ? fs.readFileSync(out(p)) : null;
  if (current && current.equals(bytes)) continue;
  if (check) { console.error(`out of date: ${p}`); drift++; continue; }
  fs.mkdirSync(path.dirname(out(p)), { recursive: true });
  fs.writeFileSync(out(p), bytes);
}
if (check && drift) process.exit(1);
console.log(check ? 'up to date' : `checked ${files.size} files`);
