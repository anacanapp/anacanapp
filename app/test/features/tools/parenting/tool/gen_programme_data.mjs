// Generates the bundled data of the programme tools (sleep training, weaning, parenting) from the React sources:
//   app/assets/i18n/parenting.<lang>.json      ← src/data/parenting/<lang>/index.ts (ParentingContent, 25 languages)
//   app/assets/i18n/parenting-sources.json     ← src/data/parenting/az/sources.ts (S: the shared SOS reference list)
//   app/assets/i18n/sleep-next.<lang>.json     ← src/data/sleep-next/<lang>.json (NextNapSection copy, verbatim)
//   app/lib/features/tools/weaning/weaning_copy.g.dart     ← src/lib/weaning-copy.ts (WEANING_COPY)
//   app/lib/features/tools/parenting/parenting_copy.g.dart ← src/lib/parenting-copy.ts (PARENTING_COPY)
// Run from the repository root:  node app/test/features/tools/parenting/tool/gen_programme_data.mjs [--check]
// --check writes nothing and exits 1 when a generated file differs from its source.
import { build } from 'esbuild';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const root = process.cwd();
const check = process.argv.includes('--check');
const out = (p) => path.join(root, p);
const LANGS = ['az', 'en', 'ru', 'tr', 'kk', 'de', 'ar', 'uz', 'ka', 'zh', 'id', 'fr', 'es', 'pt', 'vi', 'hi', 'ja', 'ko', 'pl', 'nl', 'sv', 'ky', 'et', 'tk', 'uk'];

const stub = {
  name: 'stubs',
  setup(b) {
    b.onResolve({ filter: /^@\/lib\/tr$/ }, () => ({ path: 'tr', namespace: 'stub' }));
    b.onLoad({ filter: /.*/, namespace: 'stub' }, () => ({ contents: 'export const tr = (_k, d) => d; export const formatTr = (_k, d) => d;', loader: 'js' }));
  },
};

async function load(source) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'anacan-programme-'));
  const outfile = path.join(dir, 'entry.mjs');
  await build({
    stdin: { contents: source, resolveDir: root, loader: 'ts' },
    bundle: true, platform: 'node', format: 'esm', target: 'node20', outfile, logLevel: 'error',
    alias: { '@': path.join(root, 'src') },
    plugins: [stub],
  });
  return import(pathToFileURL(outfile).href);
}

const files = new Map();
const dartString = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$').replace(/\n/g, '\\n')}'`;

function copyTable(name, header, record) {
  const lines = [
    `// Ported from: ${header}`,
    '// GENERATED by app/test/features/tools/parenting/tool/gen_programme_data.mjs. Do not edit by hand.',
    '// ignore_for_file: lines_longer_than_80_chars',
    '',
    `const Map<String, String> ${name} = {`,
  ];
  for (const [k, v] of Object.entries(record)) lines.push(`  '${k}': ${dartString(v)},`);
  lines.push('};', '');
  return lines.join('\n');
}

const copy = await load("export { WEANING_COPY } from '@/lib/weaning-copy'; export { PARENTING_COPY } from '@/lib/parenting-copy'; export { S } from '@/data/parenting/az/sources';");
files.set('app/lib/features/tools/weaning/weaning_copy.g.dart', copyTable('kWeaningCopy', 'src/lib/weaning-copy.ts (WEANING_COPY)', copy.WEANING_COPY));
files.set('app/lib/features/tools/parenting/parenting_copy.g.dart', copyTable('kParentingCopy', 'src/lib/parenting-copy.ts (PARENTING_COPY)', copy.PARENTING_COPY));
files.set('app/assets/i18n/parenting-sources.json', `${JSON.stringify(copy.S)}\n`);

for (const lang of LANGS) {
  const m = await load(`export { default } from '@/data/parenting/${lang}';`);
  files.set(`app/assets/i18n/parenting.${lang}.json`, `${JSON.stringify(m.default)}\n`);
  const sleep = path.join(root, 'src/data/sleep-next', `${lang}.json`);
  if (fs.existsSync(sleep)) files.set(`app/assets/i18n/sleep-next.${lang}.json`, `${JSON.stringify(JSON.parse(fs.readFileSync(sleep, 'utf8')))}\n`);
}

let drift = 0;
for (const [p, text] of files) {
  const current = fs.existsSync(out(p)) ? fs.readFileSync(out(p), 'utf8') : null;
  if (current === text) continue;
  if (check) { console.error(`out of date: ${p}`); drift++; continue; }
  fs.mkdirSync(path.dirname(out(p)), { recursive: true });
  fs.writeFileSync(out(p), text);
}
if (check && drift) process.exit(1);
console.log(check ? 'up to date' : `wrote ${files.size} files`);
