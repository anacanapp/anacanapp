// Generates the copy tables of the blog and books ports from the React JSON sources:
//   app/lib/features/blog/copy/blog_copy.g.dart   scripts/i18n/blog-editorial-copy.json (blogText, the keys the reader
//                                                  uses), scripts/i18n/followup36-copy.json (followupText, share /
//                                                  unavailable keys), scripts/i18n/feature37-copy.json (blog_community_share)
//   app/lib/features/books/books_copy.g.dart      scripts/i18n/books-copy.json (booksText, every key)
// Run from the repository root:  node app/test/features/blog/tool/gen_content_copy.mjs [--check]
// --check writes nothing and exits 1 when a generated file differs from its source.
import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const check = process.argv.includes('--check');
const read = (p) => JSON.parse(fs.readFileSync(path.join(root, p), 'utf8'));
const dart = (s) => JSON.stringify(s).replace(/\$/g, '\\$');

function table(name, doc, languages, keys) {
  const lines = [`const Map<String, Map<String, String>> ${name} = {`];
  for (const lang of Object.keys(languages)) {
    const entries = (keys ?? Object.keys(languages[lang])).filter((k) => typeof languages[lang][k] === 'string');
    if (!entries.length) continue;
    lines.push(`  ${dart(lang)}: {`);
    for (const key of entries) lines.push(`    ${dart(key)}: ${dart(languages[lang][key])},`);
    lines.push('  },');
  }
  lines.push('};');
  return `/// ${doc}\n${lines.join('\n')}\n`;
}

const header = (sources) => `// Ported from: ${sources}\n// GENERATED by app/test/features/blog/tool/gen_content_copy.mjs from ${sources}. Do not edit.\n// ignore_for_file: lines_longer_than_80_chars\n\n`;

const blogKeys = ['related', 'modules', 'toc', 'faq', 'references', 'feeding', 'sleep', 'diaper', 'babyGrowth', 'hospitalBag', 'calendar'];
const followupKeys = ['blog_unavailable', 'share_blog', 'link_copied', 'copy_failed', 'share_website', 'share_app', 'share_website_description', 'share_app_description', 'copy_link', 'share_send'];
const feature37Keys = ['blog_community_share'];

const files = new Map();
files.set('app/lib/features/blog/copy/blog_copy.g.dart',
  header('scripts/i18n/{blog-editorial-copy,followup36-copy,feature37-copy}.json')
  + table('kBlogEditorialCopy', '`blog-editorial-copy.json` (blogText keys of the reader).', read('scripts/i18n/blog-editorial-copy.json'), blogKeys)
  + '\n' + table('kBlogFollowupCopy', '`followup36-copy.json` languages (blog share / unavailable keys).', read('scripts/i18n/followup36-copy.json').languages, followupKeys)
  + '\n' + table('kBlogFeature37Copy', '`feature37-copy.json` languages (blog_community_share).', read('scripts/i18n/feature37-copy.json').languages, feature37Keys));
files.set('app/lib/features/books/books_copy.g.dart',
  header('scripts/i18n/books-copy.json')
  + table('kBooksCopy', '`books-copy.json` languages.', read('scripts/i18n/books-copy.json').languages));

let drift = 0;
for (const [p, text] of files) {
  const file = path.join(root, p);
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (current === text) continue;
  if (check) { console.error(`out of date: ${p}`); drift++; continue; }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
}
if (check && drift) process.exit(1);
console.log(check ? 'up to date' : `checked ${files.size} files`);
