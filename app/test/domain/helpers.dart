// Test helpers for the domain ports: a frozen clock (vi.setSystemTime) and time-zone guards.
//
// The vitest suites run in the machine zone (UTC in CI) and switch zones with `process.env.TZ`. Dart reads the
// zone once per process, so zone-specific cases only run when `flutter test` is started with that TZ (see
// app/tool/domain/run_tz_tests.sh, which runs this suite under UTC, America/New_York, Europe/Berlin and
// Asia/Baku). The guard compares this process's real offsets with the zone's known offsets.

import 'dart:convert';
import 'dart:io';

import 'package:anacan/domain/js_compat.dart';
import 'package:flutter_test/flutter_test.dart';

/// `vi.setSystemTime(t)` for the duration of the current test.
void setSystemTime(DateTime t) {
  DomainClock.setSystemTime(t);
  addTearDown(DomainClock.reset);
}

int _offsetMin(int y, int m, int d, int h) => DateTime(y, m, d, h).timeZoneOffset.inMinutes;

/// Offsets (minutes) in January, July and just after the 2026 US / EU spring changes.
List<int> zoneSignature() => [
      _offsetMin(2026, 1, 15, 12),
      _offsetMin(2026, 7, 15, 12),
      _offsetMin(2026, 3, 9, 12),
      _offsetMin(2026, 3, 30, 12),
      _offsetMin(2026, 10, 26, 12),
    ];

const Map<String, List<int>> _signatures = {
  'UTC': [0, 0, 0, 0, 0],
  'America/New_York': [-300, -240, -240, -240, -240],
  'Europe/Berlin': [60, 120, 60, 120, 60],
  'Asia/Baku': [240, 240, 240, 240, 240],
};

/// The process runs in [zone] (by its offsets).
bool inZone(String zone) {
  final want = _signatures[zone];
  if (want == null) return false;
  final got = zoneSignature();
  for (var i = 0; i < want.length; i++) {
    if (want[i] != got[i]) return false;
  }
  return true;
}

/// Skip reason unless the process runs in [zone].
Object needsZone(String zone) => inZone(zone) ? false : 'needs TZ=$zone (run app/tool/domain/run_tz_tests.sh)';

/// Known zone name of this process, or null.
String? currentZone() {
  for (final z in _signatures.keys) {
    if (inZone(z)) return z;
  }
  return null;
}

/// Loads a fixture generated by app/tool/domain/gen_fixtures.mjs for this process's zone (or the zone-free one).
Object? loadFixture(String name, {bool zoned = true}) {
  final tag = zoned ? '.${(currentZone() ?? 'none').replaceAll('/', '_')}' : '';
  final file = File('test/domain/fixtures/$name$tag.json');
  if (!file.existsSync()) return null;
  return jsonDecode(file.readAsStringSync());
}

/// Fixture skip reason.
Object fixtureSkip(String name, {bool zoned = true}) =>
    loadFixture(name, zoned: zoned) == null ? 'no $name fixture for zone ${currentZone() ?? 'unknown'}' : false;

/// Local wall-clock parts like the vitest `ymd` helper: [year, month, day, hour].
List<int>? ymd(DateTime? d) => d == null ? null : [d.year, d.month, d.day, d.hour];

/// Deep numeric-tolerant equality for fixture comparison (JS and Dart libm may differ in the last ulp).
void expectJsonClose(Object? actual, Object? expected, {String path = r'$', double tol = 1e-9}) {
  if (expected is num && actual is num) {
    if (expected.isNaN) {
      expect(actual.isNaN, isTrue, reason: path);
      return;
    }
    final scale = expected.abs() > 1 ? expected.abs() : 1;
    expect((actual - expected).abs() <= tol * scale, isTrue, reason: '$path: $actual != $expected');
    return;
  }
  if (expected is List) {
    expect(actual, isA<List>(), reason: path);
    final a = actual as List;
    expect(a.length, expected.length, reason: '$path length');
    for (var i = 0; i < expected.length; i++) {
      expectJsonClose(a[i], expected[i], path: '$path[$i]', tol: tol);
    }
    return;
  }
  if (expected is Map) {
    expect(actual, isA<Map>(), reason: path);
    final a = actual as Map;
    expect(a.keys.toSet(), expected.keys.toSet(), reason: '$path keys');
    for (final k in expected.keys) {
      expectJsonClose(a[k], expected[k], path: '$path.$k', tol: tol);
    }
    return;
  }
  expect(actual, expected, reason: path);
}
